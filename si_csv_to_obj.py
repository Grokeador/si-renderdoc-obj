#!/usr/bin/env python3
"""
SI-RenderDoc-OBJ (by SI NEWS) — Zero-dependency RenderDoc CSV Mesh to Wavefront .OBJ/.MTL Converter.
100% Python 3 standard library (csv, math, pathlib).
"""
from __future__ import annotations
import argparse
import csv
import io
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple


def _find_col_triplet(headers: List[str], prefixes: Tuple[str, ...]) -> Optional[Tuple[str, str, str]]:
    norm = {h.strip().upper(): h.strip() for h in headers}
    for p in prefixes:
        kx, ky, kz = f"{p}.X", f"{p}.Y", f"{p}.Z"
        if kx in norm and ky in norm and kz in norm:
            return (norm[kx], norm[ky], norm[kz])
    return None


def _find_col_pair(headers: List[str], prefixes: Tuple[str, ...]) -> Optional[Tuple[str, str]]:
    norm = {h.strip().upper(): h.strip() for h in headers}
    for p in prefixes:
        ku, kv = f"{p}.X", f"{p}.Y"
        if ku in norm and kv in norm:
            return (norm[ku], norm[kv])
        ku2, kv2 = f"{p}.U", f"{p}.V"
        if ku2 in norm and kv2 in norm:
            return (norm[ku2], norm[kv2])
    return None


def convert_renderdoc_csv_to_obj(
    csv_text: str,
    flip_v: bool = True,
    mtllib_name: Optional[str] = None,
) -> Dict[str, object]:
    reader = csv.DictReader(io.StringIO(csv_text.strip()))
    headers = list(reader.fieldnames or [])
    if not headers:
        raise ValueError("Empty CSV or missing header row.")

    pos_cols = _find_col_triplet(headers, ("POSITION", "POS", "SV_POSITION", "IN_POSITION", "ATTRIBUTE0"))
    if not pos_cols:
        raise ValueError(f"Could not find POSITION.x/.y/.z columns in headers: {headers}")

    norm_cols = _find_col_triplet(headers, ("NORMAL", "NRM", "IN_NORMAL"))
    uv_cols = _find_col_pair(headers, ("TEXCOORD0", "TEXCOORD", "UV", "IN_UV"))
    upper_map = {h.strip().upper(): h for h in headers}
    idx_col = upper_map.get("IDX") or upper_map.get("INDEX") or upper_map.get("VTX")

    vert_map: Dict[int, int] = {}
    positions: List[Tuple[float, float, float]] = []
    normals: List[Tuple[float, float, float]] = []
    uvs: List[Tuple[float, float]] = []
    face_indices: List[int] = []

    for row_num, row in enumerate(reader):
        raw_idx = int(row[idx_col]) if (idx_col and row.get(idx_col, "").strip().isdigit()) else row_num
        if raw_idx not in vert_map:
            px = float(row[pos_cols[0]])
            py = float(row[pos_cols[1]])
            pz = float(row[pos_cols[2]])
            positions.append((px, py, pz))
            if uv_cols and row.get(uv_cols[0]) is not None and row.get(uv_cols[1]) is not None:
                u = float(row[uv_cols[0]])
                v = float(row[uv_cols[1]])
                uvs.append((u, (1.0 - v) if flip_v else v))
            if norm_cols and row.get(norm_cols[0]) is not None:
                nx = float(row[norm_cols[0]])
                ny = float(row[norm_cols[1]])
                nz = float(row[norm_cols[2]])
                normals.append((nx, ny, nz))
            vert_map[raw_idx] = len(positions)
        face_indices.append(vert_map[raw_idx])

    lines: List[str] = ["# Generated by SI-RenderDoc-OBJ (https://github.com/Grokeador/si-renderdoc-obj)"]
    if mtllib_name:
        lines.append(f"mtllib {mtllib_name}")
        lines.append("usemtl CapturedMaterial")

    for px, py, pz in positions:
        lines.append(f"v {px:.6f} {py:.6f} {pz:.6f}")
    for u, v in uvs:
        lines.append(f"vt {u:.6f} {v:.6f}")
    for nx, ny, nz in normals:
        lines.append(f"vn {nx:.6f} {ny:.6f} {nz:.6f}")

    has_uv = len(uvs) == len(positions) and len(uvs) > 0
    has_nrm = len(normals) == len(positions) and len(normals) > 0

    tri_count = len(face_indices) // 3
    for t in range(tri_count):
        i0, i1, i2 = face_indices[t * 3], face_indices[t * 3 + 1], face_indices[t * 3 + 2]
        if i0 == i1 or i1 == i2 or i0 == i2:
            continue
        if has_uv and has_nrm:
            lines.append(f"f {i0}/{i0}/{i0} {i1}/{i1}/{i1} {i2}/{i2}/{i2}")
        elif has_uv:
            lines.append(f"f {i0}/{i0} {i1}/{i1} {i2}/{i2}")
        else:
            lines.append(f"f {i0} {i1} {i2}")

    return {
        "objText": "\n".join(lines) + "\n",
        "vertexCount": len(positions),
        "triangleCount": tri_count,
        "hasUV": has_uv,
        "hasNormals": has_nrm,
    }


def build_mtl_text(texture_filename: str = "albedo.png") -> str:
    return (
        "# Generated by SI-RenderDoc-OBJ\n"
        "newmtl CapturedMaterial\n"
        "Ka 1.000 1.000 1.000\n"
        "Kd 1.000 1.000 1.000\n"
        "Ks 0.100 0.100 0.100\n"
        "d 1.0\n"
        f"map_Kd {texture_filename}\n"
    )


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="SI-RenderDoc-OBJ Converter (by SI NEWS)")
    parser.add_argument("--input", type=str, required=True, help="Input RenderDoc CSV file")
    parser.add_argument("--out", type=str, required=True, help="Output Wavefront .obj file")
    parser.add_argument("--texture", type=str, default="", help="Optional albedo texture filename for .mtl")
    parser.add_argument("--no-flip-v", action="store_true", help="Do not flip V texture coordinate")
    args = parser.parse_args(argv)

    csv_text = Path(args.input).read_text(encoding="utf-8", errors="ignore")
    out_path = Path(args.out)
    mtl_name = out_path.with_suffix(".mtl").name if args.texture else None
    res = convert_renderdoc_csv_to_obj(csv_text, flip_v=not args.no_flip_v, mtllib_name=mtl_name)
    out_path.write_text(str(res["objText"]), encoding="utf-8")
    if args.texture and mtl_name:
        out_path.with_suffix(".mtl").write_text(build_mtl_text(args.texture), encoding="utf-8")
    print(f"[OK] Wrote {out_path} ({res['vertexCount']} vertices, {res['triangleCount']} triangles)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
